  update accounts set balance = 519,    bank = 'Garanti' where name = 'Vadesiz EUR'  and is_active is true;
  update accounts set balance = 175                      where name = 'Sparkasse'    and is_active is true;
  update accounts set balance = 4020                     where name = 'Revolut'      and is_active is true;
  update accounts set balance = 1826                     where name = 'N26'          and is_active is true;

  -- Denizbank: 558.037 − 240.000 (bugün BTD'ye) = 318.037
  if exists (select 1 from accounts where name = 'Denizbank Vadesiz' and is_active is true) then
    update accounts set balance = 318037 where name = 'Denizbank Vadesiz' and is_active is true;
  else
    insert into accounts (name, bank, type, currency, balance, notes, is_active, user_id)
    values ('Denizbank Vadesiz', 'Denizbank', 'vadesiz', 'TRY', 318037,
            '558.037 − 240.000 (21.10 BTD ödemesi)', true, owner);
  end if;

  -- Evdeki nakit
  if exists (select 1 from accounts where name = 'Nakit (Evde)' and is_active is true) then
    update accounts set balance = 30000 where name = 'Nakit (Evde)' and is_active is true;
  else
    insert into accounts (name, bank, type, currency, balance, notes, is_active, user_id)
    values ('Nakit (Evde)', 'Nakit', 'vadesiz', 'TRY', 30000, 'Elde tutulan nakit', true, owner);
  end if;

  -- ===== YATIRIMLAR =====
  update investments set is_active = false where symbol = 'GARAN' and is_active is true;  -- satıldı

  select id into inv_tnz from investments where symbol = 'TNZTP' and is_active is true limit 1;
  update investments set quantity = 7000, avg_cost = 29.49 where id = inv_tnz;
  delete from investment_snapshots where investment_id = inv_tnz and snapshot_date = '2026-10-21';
  insert into investment_snapshots (investment_id, snapshot_date, price, total_value, total_value_try, user_id)
  values (inv_tnz, '2026-10-21', 22.72, 159040, 159040, owner);   -- 7.000 × 22,72

  -- THY fonu tasfiye: artık yatırım değil, alacak
  update investments set is_active = false where type = 'fon' and is_active is true;
  insert into debt_records (person_name, type, amount, currency, description,
                            transaction_date, due_date, is_settled, notes, user_id)
  select 'THY Fonu (tasfiye)', 'alacak', 55750, 'TRY', 'Fon tasfiyesinden beklenen ödeme',
         '2026-10-21', null, false,
         'Fona 200.000 girilmişti · beklenen 55.750 · kesinleşince güncelle', owner
   where not exists (select 1 from debt_records where person_name = 'THY Fonu (tasfiye)');

  -- ===== ALACAKLAR =====
  -- Zanzibar: 3.000 EUR'nun 1.000'i tahsil edildi
  select id into d_zanzibar from debt_records
   where person_name = 'Zanzibar Projesi' and is_settled is false limit 1;
  if d_zanzibar is not null then
    update debt_records
       set amount = 2000,
           paid_amount = coalesce(paid_amount, 0) + 1000,
           total_amount = coalesce(total_amount, 3000)
     where id = d_zanzibar;
    insert into debt_transactions (debt_id, type, amount, currency, transaction_date, notes, user_id)
    select d_zanzibar, 'tahsilat', 1000, 'EUR', '2026-10-21', 'Revolut''a geldi', owner
     where not exists (select 1 from debt_transactions
                        where debt_id = d_zanzibar and transaction_date = '2026-10-21' and amount = 1000);
  end if;

  insert into debt_records (person_name, type, amount, currency, description,
                            transaction_date, due_date, is_settled, user_id)
  select 'Mimosso UG', 'alacak', 400, 'EUR', 'Verilen borç', '2026-10-21', null, false, owner
   where not exists (select 1 from debt_records
                      where person_name = 'Mimosso UG' and transaction_date = '2026-10-21');

