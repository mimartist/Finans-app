  if not exists (select 1 from recurring_expenses
                  where name = 'İnfosec Tadilat — Yüksel Artık iş avansı'
                     or (name = 'İnfosec Tadilat — Yüksel iş avansı' and expense_date = '2026-10-21')) then
    insert into recurring_expenses (name, category, amount, currency, payment_day,
                                    expense_type, expense_date, is_variable,
                                    remind_days_before, is_active, user_id)
    values ('İnfosec Tadilat — Yüksel Artık iş avansı', 'personel', 5000, 'TRY', 21,
            'one_time', '2026-10-21', false, 1, true, owner)
    returning id into e_avans;
