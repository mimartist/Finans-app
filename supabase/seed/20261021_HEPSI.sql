-- ─── 1. TABLO VE KOLONLAR ───────────────────────────────────────────────────
create table if not exists projects (
  id              bigint generated by default as identity primary key,
  name            text not null,
  client          text,
  contract_amount numeric,
  vat_rate        numeric not null default 20,
  collected       numeric not null default 0,
  status          text not null default 'devam',
  start_date      date,
  end_date        date,
  notes           text,
  user_id         uuid references auth.users(id) on delete cascade,
  created_at      timestamptz not null default now()
);

alter table recurring_expenses add column if not exists project_id bigint references projects(id) on delete set null;
alter table recurring_expenses add column if not exists vat_rate numeric;
alter table debt_records       add column if not exists project_id bigint references projects(id) on delete set null;
alter table debt_records       add column if not exists vat_rate numeric;
alter table recurring_payments add column if not exists account_id bigint references accounts(id) on delete set null;
alter table recurring_payments add column if not exists account_amount numeric;

create index if not exists recurring_expenses_project_idx on recurring_expenses (project_id);
create index if not exists debt_records_project_idx       on debt_records (project_id);

alter table projects enable row level security;
drop policy if exists projects_owner_all on projects;
create policy projects_owner_all on projects for all to authenticated
  using (user_id is null or user_id = auth.uid())
  with check (user_id is null or user_id = auth.uid());

update debt_records set vat_rate = 20 where person_name = 'İnfosec' and vat_rate is null;

