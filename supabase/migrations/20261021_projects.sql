-- ============================================================================
-- PROJELER — ön muhasebe
--
-- Amaç: bir işin gelir ve giderlerini AYNI kayıtlar üzerinden takip etmek.
-- Ayrı bir defter açılmıyor; mevcut alacak ve gider kayıtlarına proje etiketi
-- ekleniyor. Böylece aynı para iki yerde yaşamıyor — bu oturumda temizlediğimiz
-- hataların (Nuhoğlu hem gider hem kredi, kart hem kart hem gider) kaynağı
-- tam olarak buydu.
--
-- projects tablosu yalnızca kayıtlardan TÜRETİLEMEYEN bilgiyi tutar:
-- sözleşme bedeli, KDV oranı ve bugüne dek tahsil edilen tutar. Kalan alacak,
-- maliyet ve kâr; etiketli kayıtlardan hesaplanır.
-- ============================================================================

create table if not exists projects (
  id              bigint generated by default as identity primary key,
  name            text not null,
  client          text,
  contract_amount numeric,                 -- sözleşme bedeli, KDV HARİÇ
  vat_rate        numeric not null default 20,
  collected       numeric not null default 0,  -- bugüne dek tahsil edilen, KDV DAHİL
  status          text not null default 'devam',  -- devam | tamamlandi | iptal
  start_date      date,
  end_date        date,
  notes           text,
  user_id         uuid references auth.users(id) on delete cascade,
  created_at      timestamptz not null default now()
);

-- Kayıtları projeye bağlayan etiketler
alter table recurring_expenses
  add column if not exists project_id bigint references projects(id) on delete set null;

-- Giderin KDV oranı: taşeron faturası 20, maaş gibi KDV'siz kalemler null/0.
-- Tutar her zaman kasadan çıkan (KDV dahil) rakamdır; bu kolon yalnızca
-- muhasebe kârını hesaplarken KDV'yi ayırmak için kullanılır.
alter table recurring_expenses
  add column if not exists vat_rate numeric;

alter table debt_records
  add column if not exists project_id bigint references projects(id) on delete set null;

create index if not exists recurring_expenses_project_idx on recurring_expenses (project_id);
create index if not exists debt_records_project_idx       on debt_records (project_id);

-- Diğer tablolarla aynı RLS modeli (bkz. 20260702_rls_user_id.sql)
alter table projects enable row level security;
drop policy if exists projects_owner_all on projects;
create policy projects_owner_all on projects
  for all to authenticated
  using (user_id is null or user_id = auth.uid())
  with check (user_id is null or user_id = auth.uid());
