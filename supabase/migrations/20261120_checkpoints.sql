-- Üç aylık nakit kontrol noktaları.
-- target_amount: o tarihte en az olması gereken likit varlık (nakit + fon + hisse).
-- Hiç ek iş gelmediği senaryodan türetildi; altına düşmek "plandan kötü" demek.
-- actual_amount: kontrol günü uygulamadan kaydedilen gerçek değer.
create table if not exists checkpoints (
  id            bigint generated by default as identity primary key,
  check_date    date not null,
  target_amount numeric not null,
  actual_amount numeric,
  actual_date   date,
  note          text,
  user_id       uuid references auth.users(id) on delete cascade,
  created_at    timestamptz not null default now()
);

alter table checkpoints enable row level security;
drop policy if exists checkpoints_owner_all on checkpoints;
create policy checkpoints_owner_all on checkpoints for all to authenticated
  using (user_id is null or user_id = auth.uid())
  with check (user_id is null or user_id = auth.uid());

